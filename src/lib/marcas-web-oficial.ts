/** Normaliza el nombre de marca igual que las claves del mapa. */
export function normalizarMarca(marca: string): string {
  return marca
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]/g, "");
}

/**
 * Web oficial del fabricante de una marca, o null si no hay ninguna verificada
 * en el repo. Es la web del fabricante (raíz), no un deep-link de modelo: sirve
 * como fuente de la ficha cuando esta no trae su propia fuenteUrl.
 */
export function webOficialMarca(marca: string | null | undefined): string | null {
  if (!marca) return null;
  return MARCAS_WEB_OFICIAL[normalizarMarca(marca)] ?? null;
}
