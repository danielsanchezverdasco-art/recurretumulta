import { chromium, devices } from 'playwright';
import fs from 'fs';
const B=process.argv[2], mime=process.argv[3]??'', name=process.argv[4]??'multa-daniel.pdf';
const b=await chromium.launch(); const ctx=await b.newContext({...devices['Pixel 7']});
const pg=await ctx.newPage(); const js=[];
pg.on('response',r=>{const u=r.url(); if(/AnalizadorMulta-|\/index-.*\.js/.test(u)) js.push(u.split('/').pop());});
await pg.goto(B+'/',{waitUntil:'networkidle'});
await pg.locator('input[type=file][accept*="pdf"]').first().setInputFiles({name,mimeType:mime,buffer:fs.readFileSync(process.env.F||'/workspace/analizador/real/multa-daniel.pdf')});
await pg.waitForTimeout(1000);
await pg.getByRole('button',{name:/Analizar multa con IA gratis/}).first().click();
const t0=Date.now();
await pg.waitForFunction(()=>/Resultado del análisis IA|No hemos podido leer|tardando más/i.test(document.body.innerText),null,{timeout:220000}).catch(()=>{});
const txt=await pg.evaluate(()=>document.body.innerText);
console.log('js',[...new Set(js)].join(','),'secs',(Date.now()-t0)/1000);
console.log('warning:',/No hemos podido leer/i.test(txt),'| expediente:',txt.includes('719473837'),'| 1919MPN:',txt.includes('1919MPN'));
const i=txt.search(/%/); console.log(txt.slice(Math.max(0,i-200),i+500));
await pg.screenshot({path:'/workspace/analizador/real/movil-'+(mime||'vacio').replace('/','_')+'.png',fullPage:false});
await b.close();
